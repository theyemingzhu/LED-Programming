import { test, expect } from '@playwright/test';
const mapperProject = { format:'lightweaver.mapper-project',schemaVersion:3,version:3,svgSource:'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><path d="M10 50 L90 50"/></svg>',strips:[{id:'synthetic-path',name:'Synthetic path',pathData:'M10 50 L90 50',pixelCount:4,color:'#06d6a0'}],patterns:[{id:'green',name:'Green',code:'return {r:0,g:255,b:0};'}],activePatternId:'green' };
test('Mapper opens from Layout, preserves a saved project and adds reviewed paths without card writes',async({page},testInfo)=>{
  const writes:string[]=[];
  await page.route('http://lightweaver.local/**',async route=>{if(route.request().method()!=='GET')writes.push(route.request().url());await route.abort();});
  await page.goto('/#screen=layout');
  await page.getByRole('link',{name:'Mapper',exact:true}).click();
  const frame=page.frameLocator('iframe[title="LED Mapper"]');
  await expect(frame.getByRole('button',{name:'Add paths to Studio'})).toBeVisible();
  await expect(frame.locator('#btn-load')).toBeVisible();
  const picker = page.waitForEvent('filechooser');
  await frame.locator('#btn-load').click();
  await (await picker).setFiles({name:'synthetic.mapper.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(mapperProject))});
  await frame.getByRole('button',{name:'OK',exact:true}).click();
  await expect(frame.locator('#strips-list')).toContainText('Synthetic path');
  await expect(frame.getByRole('button',{name:'Add paths to Studio'})).toBeVisible();
  const download = page.waitForEvent('download');
  await frame.locator('#btn-save').click();
  const savedFile = await download;
  const savedPath = testInfo.outputPath('saved-mapper.json');
  await savedFile.saveAs(savedPath);
  const saved = JSON.parse(await (await import('node:fs/promises')).readFile(savedPath,'utf8'));
  expect(saved.format).toBe(mapperProject.format);
  expect(saved.strips[0].pathData).toBe(mapperProject.strips[0].pathData);
  expect(saved.patterns.find((pattern:any)=>pattern.id==='green').code).toBe(mapperProject.patterns[0].code);
  await page.screenshot({path:testInfo.outputPath('mapper-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('mapper-phone.png')});
  await frame.getByRole('button',{name:'Add paths to Studio'}).click();
  await expect(page.getByTestId('mapper-handoff-review')).toContainText('1 path');
  await page.getByRole('button',{name:'Add to Layout',exact:true}).click();
  await expect(page).toHaveURL(/screen=layout/);
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('lw_autosave_v3')||'{}').layout?.strips?.some((s:any)=>s.name==='Synthetic path'))).toBe(true);
  expect(writes).toEqual([]);
});
